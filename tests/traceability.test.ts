import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { Store } from '../server/store.js';
import type { EntityRef } from '../server/schema.js';

async function fixture(t: { after: (fn: () => Promise<unknown>) => void }) {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'mkagile-trace-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const store = new Store(directory); await store.init();
  const board = await store.createBoard({ title: 'Projet' });
  const column = await store.createColumn(board.id, { title: 'À faire' });
  const card = await store.createCard(board.id, column.id, { title: 'Implémentation', points: 5 });
  const decision = await store.createDecision(board.id, { title: 'Choix initial', status: 'accepted', outcome: 'Solution A', rationale: 'Adaptée au projet' });
  return { directory, store, board, column, card, decision };
}
const ref = (kind: EntityRef['kind'], id: string): EntityRef => ({ kind, id });
test('generic links are bidirectional and preserve directed meaning alongside legacy decision links', async t => {
  const { store, board, card, decision } = await fixture(t);
  const requirement = await store.createKnowledge(board.id, { kind: 'requirement', title: 'Usage local', content: '**Hors ligne**' });
  const document = await store.createKnowledge(board.id, { kind: 'document', title: 'Conception', url: 'https://example.org/design' });
  await store.createRelation(board.id, { source: ref('card', card.id), target: ref('requirement', requirement.id), type: 'implements' });
  const link = await store.createRelation(board.id, { source: ref('document', document.id), target: ref('decision', decision.id), type: 'documents' });
  await store.updateDecision(board.id, decision.id, { links: [{ kind: 'card', target: card.id }] });
  const fromTask = await store.listRelations(board.id, ref('card', card.id));
  assert.equal(fromTask.length, 2); assert.ok(fromTask.some(r => 'other' in r && (r.other as EntityRef).id === decision.id));
  const fromDecision = await store.listRelations(board.id, ref('decision', decision.id));
  assert.equal(fromDecision.length, 2); assert.ok(fromDecision.some(r => r.id === link.id && 'outgoing' in r && r.outgoing === false));
  const fromRequirement = await store.listRelations(board.id, ref('requirement', requirement.id));
  assert.equal(fromRequirement[0].type, 'implements'); assert.ok('outgoing' in fromRequirement[0] && !fromRequirement[0].outgoing);
  assert.deepEqual((await store.getCard(board.id, card.id)).dependencies, []);
});
test('self, duplicate, foreign, deleted and invalid-URL relations are rejected atomically', async t => {
  const { store, board, card, decision, directory } = await fixture(t);
  const source = ref('card', card.id), target = ref('decision', decision.id);
  await store.createRelation(board.id, { source, target });
  const other = await store.createBoard({ title: 'Autre projet' });
  const foreign = await store.createKnowledge(other.id, { kind: 'document', title: 'Ailleurs' });
  const deleted = await store.createKnowledge(board.id, { kind: 'requirement', title: 'Ancien besoin' }); await store.deleteKnowledge(board.id, deleted.id);
  const filename = path.join(directory, `${board.id}.json`), before = await readFile(filename, 'utf8');
  for (const values of [{ source, target: source }, { source, target }, { source: target, target: source }, { source, target: ref('document', foreign.id) }, { source, target: ref('requirement', deleted.id) }, { source, target: ref('url', 'javascript:alert(1)') }, { source, target: ref('url', 'invalid') }]) await assert.rejects(store.createRelation(board.id, values));
  await assert.rejects(store.createKnowledge(board.id, { kind: 'document', title: 'Erreur', url: 'invalid' }));
  assert.equal(await readFile(filename, 'utf8'), before);
});
test('supersession records direct/transitive impact atomically, following Gantt successors and external links', async t => {
  const { store, board, card, decision, column, directory } = await fixture(t);
  const successor = await store.createCard(board.id, column.id, { title: 'Validation', dependencies: [card.id] });
  const document = await store.createKnowledge(board.id, { kind: 'document', title: 'Conception' });
  const requirement = await store.createKnowledge(board.id, { kind: 'requirement', title: 'Besoin' });
  await store.createRelation(board.id, { source: ref('card', card.id), target: ref('document', document.id), type: 'documents' });
  await store.createRelation(board.id, { source: ref('document', document.id), target: ref('requirement', requirement.id), type: 'validates' });
  await store.updateDecision(board.id, decision.id, { links: [{ kind: 'card', target: card.id }, { kind: 'url', target: 'https://example.org/spec' }] });
  const unrelated = await store.createCard(board.id, column.id, { title: 'Sans rapport' });
  const replacement = await store.createDecision(board.id, { title: 'Solution B', status: 'accepted', outcome: 'B', rationale: 'Nouveau contexte' });
  const before = await store.getBoard(board.id);
  const preview = await store.analyzeDecisionImpact(board.id, decision.id);
  assert.equal(preview.affected.length, 5); assert.equal(preview.reviews.length, 0);
  assert.deepEqual(await store.getBoard(board.id), before);
  await assert.rejects(store.analyzeDecisionImpact(board.id, decision.id, true), /remplacée/);
  await store.updateDecision(board.id, decision.id, { status: 'superseded', supersededBy: replacement.id });
  const reviews = await store.listImpactReviews(board.id);
  assert.equal(reviews.length, 5);
  assert.equal(reviews.find(r => r.entity.id === card.id)!.distance, 1);
  assert.equal(reviews.find(r => r.entity.id === successor.id)!.distance, 2);
  assert.equal(reviews.find(r => r.entity.id === requirement.id)!.distance, 3);
  assert.equal(reviews.some(r => [replacement.id, unrelated.id].includes(r.entity.id)), false);
  assert.equal(reviews.find(r => r.entity.kind === 'url')!.entity.id, 'https://example.org/spec');
  const restored = await new Store(directory).getBoard(board.id);
  assert.equal(restored.impactReviews.length, 5); assert.deepEqual(restored.pointHistory, before.pointHistory);
  assert.equal(restored.columns[0].cards.find(c => c.id === card.id)!.completed, false);
  assert.deepEqual(restored.impactReviews.find(r => r.entity.id === requirement.id)!.path.map(r => r.id), [decision.id, card.id, document.id, requirement.id]);
});
test('impact handles cycles, propagates Gantt forwards only and does not traverse supersededBy', async t => {
  const { store, board, card, column, decision } = await fixture(t);
  const previous = await store.createCard(board.id, column.id, { title: 'Prérequis' });
  await store.updateCard(board.id, card.id, { dependencies: [previous.id] });
  const doc = await store.createKnowledge(board.id, { kind: 'document', title: 'Document' });
  const source = ref('decision', decision.id), task = ref('card', card.id), document = ref('document', doc.id);
  await store.createRelation(board.id, { source, target: task });
  await store.createRelation(board.id, { source: task, target: document });
  await store.createRelation(board.id, { source: document, target: source });
  const replacement = await store.createDecision(board.id, { title: 'Remplacement', status: 'accepted', outcome: 'B', rationale: 'Nouveau besoin' });
  await store.updateDecision(board.id, decision.id, { status: 'superseded', supersededBy: replacement.id });
  const impact = await store.analyzeDecisionImpact(board.id, decision.id);
  assert.equal(impact.affected.length, 2); assert.equal(impact.affected.some(i => i.entity.id === previous.id), false);
  assert.equal(impact.affected.some(i => i.entity.id === replacement.id), false);
});
test('review notes persist, reject conflicts, survive unlink/delete and can be reopened without changing tasks', async t => {
  const { store, board, card, decision, directory } = await fixture(t);
  const relation = await store.createRelation(board.id, { source: ref('decision', decision.id), target: ref('card', card.id) });
  const replacement = await store.createDecision(board.id, { title: 'Remplacement', status: 'accepted', outcome: 'B', rationale: 'Nouveau besoin' });
  await store.updateDecision(board.id, decision.id, { status: 'superseded', supersededBy: replacement.id });
  const review = (await store.listImpactReviews(board.id))[0];
  const done = await store.reviewImpact(board.id, review.id, { reviewed: true, note: 'Code vérifié', expectedUpdatedAt: review.updatedAt });
  assert.ok(done.reviewedAt); assert.equal((await store.listImpactReviews(board.id)).length, 0);
  await assert.rejects(store.reviewImpact(board.id, review.id, { reviewed: false, expectedUpdatedAt: review.updatedAt }), /changé/);
  await store.analyzeDecisionImpact(board.id, decision.id, true);
  assert.equal((await store.listImpactReviews(board.id)).length, 0);
  await store.deleteRelation(board.id, relation.id); await store.deleteCard(board.id, card.id);
  const restored = (await new Store(directory).listImpactReviews(board.id, 'all'))[0];
  assert.equal(restored.entityTitle, card.title); assert.equal(restored.note, 'Code vérifié');
  await store.reviewImpact(board.id, restored.id, { reviewed: false, expectedUpdatedAt: restored.updatedAt });
  assert.equal((await store.listImpactReviews(board.id)).length, 1);
  assert.equal((await store.listImpactReviews(board.id))[0].note, 'Code vérifié');
});
test('knowledge updates and soft deletion protect versions and legacy project JSON loads empty relations', async t => {
  const { store, board, directory } = await fixture(t);
  const filename = path.join(directory, `${board.id}.json`), legacy = JSON.parse(await readFile(filename, 'utf8'));
  delete legacy.knowledge; delete legacy.relations; delete legacy.impactReviews; await writeFile(filename, JSON.stringify(legacy));
  assert.deepEqual((await store.getBoard(board.id)).relations, []);
  const item = await store.createKnowledge(board.id, { kind: 'requirement', title: 'Exigence', content: '**Version initiale**' });
  const updated = await store.updateKnowledge(board.id, item.id, { content: '# Version revue' }, item.updatedAt);
  assert.ok(updated.updatedAt > item.updatedAt);
  await assert.rejects(store.updateKnowledge(board.id, item.id, { title: 'Obsolète' }, item.updatedAt), /changé/);
  await assert.rejects(store.deleteKnowledge(board.id, item.id, item.updatedAt), /changé/);
  await assert.rejects(store.updateKnowledge(board.id, item.id, { kind: 'document' }));
  await store.deleteKnowledge(board.id, item.id, updated.updatedAt);
  assert.equal((await store.listKnowledge(board.id)).length, 0); assert.equal((await store.listKnowledge(board.id, true)).length, 1);
  await assert.rejects(store.updateKnowledge(board.id, item.id, { title: 'Réécriture' }), /lecture seule/);
});
